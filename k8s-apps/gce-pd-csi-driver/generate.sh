#!/bin/sh
# Render the upstream PD CSI driver (pinned in kustomize/kustomization.yaml)
# into the Helm chart. Re-run after changing the version or patches.
set -eu
cd "$(dirname "$0")"
{
  echo "# GENERATED by generate.sh from kustomize/ - do not edit by hand"
  kubectl kustomize kustomize/
} > templates/driver.yaml
